const std = @import("std");
const lp = @import("lightpanda");

/// Report the local version without contacting the upstream release service.
pub fn inform(_: std.mem.Allocator, _: *const lp.Config, writer: *std.Io.Writer) !void {
    try writer.print("{s} (automatic update checks are unavailable in this fork)\n", .{lp.build_config.version});
    try writer.flush();
}
